	AREA RESET,DATA,READONLY
	EXPORT __Vectors
__Vectors
	DCD 0x10001000
	DCD Reset_Handler
	ALIGN
	AREA mycode,CODE,READONLY
	ENTRY
	EXPORT Reset_Handler
Reset_Handler
	LDR R0,=SRC
	MOV R2, #N
	LDR R1, =SUM
UP	LDR R3,[R0],#4
	ADDS R4,R3
	ADC R5,#0
	SUBS R2,#1
	BNE UP
	STR R4,[R1],#4
	STR R5, [R1]
STOP B STOP
N	EQU	10 
SRC DCD 0x1,0x2,0x3,0x4,0x10,0x60,0x70,0x91,0x69,0x89
	AREA MYDATA,DATA,READWRITE
SUM DCD 0,0
	END